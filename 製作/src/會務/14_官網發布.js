// 發布：選官網資料夾 → 寫入 資料/site-data.js → 複製下載檔與公開照片到 資料/檔案/
async function 發布到官網資料夾() {
  try {
    const 夾 = await window.showDirectoryPicker({ id: "官網資料夾", mode: "readwrite" });
    if (夾.requestPermission && (await 夾.requestPermission({ mode: "readwrite" })) !== "granted") throw new Error("沒有取得資料夾的寫入權限");
    let 有首頁 = true;
    try { await 夾.getFileHandle("index.html"); } catch (e) { 有首頁 = false; }
    if (!有首頁 && !(await 確認("這個資料夾裡沒有 index.html，看起來不是官網資料夾。仍要寫入嗎？", "仍要寫入"))) return;
    const 時間 = 現在();
    const 官網資料 = 產生官網資料(狀態.資料, 時間);
    const 資料夾 = await 夾.getDirectoryHandle("資料", { create: true });
    const 檔案夾 = await 資料夾.getDirectoryHandle("檔案", { create: true });
    // 要複製的附件：下載檔＋公開活動的照片
    const 附件們 = 集合("下載").filter(function (d) { return d.公開 !== false && d.附件; }).map(function (d) { return d.附件; });
    集合("活動").filter(function (a) { return a.公開 && a.成果公開; }).forEach(function (a) { (a.照片 || []).forEach(function (p) { 附件們.push(p); }); });
    let 複製 = 0, 缺 = 0;
    for (const 路徑 of 附件們) {
      const f = await 讀附件(路徑);
      if (!f) { 缺++; continue; }
      await 寫檔(檔案夾, 路徑.split("/").pop(), f);
      複製++;
    }
    await 寫檔(資料夾, "site-data.js", 官網資料檔內容(官網資料));
    更新設定({ 最後發布: 時間, 最後發布人: 操作者() });
    記錄操作("發布", "官網", "發布官網資料（附件 " + 複製 + " 個）");
    提示("已發布到官網：資料檔＋" + 複製 + " 個檔案" + (缺 ? "（" + 缺 + " 個附件找不到）" : "") + "。記得存檔。");
    重新繪製();
  } catch (e) {
    if (e && e.name === "AbortError") return;
    提示("發布失敗：" + e.message, true);
  }
}
