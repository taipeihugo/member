// 畫某一種官網內容的列表（新增、編輯、刪除）
function 繪製官網集合(區, 名) {
  const 定 = 官網內容定義(名);
  const 表 = 資料表({
    匯出檔名: "官網_" + 名,
    資料: function () { return 集合(定.集合); },
    預設排序: 定.排序,
    欄位: 定.列,
    點列: function (r) { 編輯官網項目(名, r.id, 表.重繪); },
    工具: [h("button", { class: "鈕 主 小", type: "button", id: "新增官網項目鈕", onclick: function () { 編輯官網項目(名, null, 表.重繪); } }, "＋ 新增")]
  });
  if (定.註) 區.appendChild(h("p", { class: "次要字 小字" }, 定.註));
  區.appendChild(表.元素);
}

// 新增或編輯一個官網項目（下載檔案會把檔案存進 附件/官網下載/）
function 編輯官網項目(名, id, 完成後) {
  const 定 = 官網內容定義(名);
  const 原 = id ? 找(定.集合, id) : null;
  const 選項 = {};
  if (原) {
    選項.額外按鈕 = [{
      文字: "刪除", 危: true, 動作: async function (關) {
        if (!(await 確認("確定刪除這一項？", "刪除"))) return false;
        if (原.附件) await 刪附件(原.附件);
        刪除紀錄(定.集合, id);
        關(null);
        完成後();
      }
    }];
  }
  return 表單對話框((原 ? "編輯" : "新增") + "：" + 名, 定.欄位, 原 || {}, async function (值) {
    const 檔 = 值.檔案;
    delete 值.檔案;
    if (名 === "下載檔案") {
      if (!檔 && !(原 && 原.附件)) return "請選擇要提供下載的檔案";
      if (檔) {
        try {
          const 路徑 = await 存附件(["官網下載"], 檔);
          if (原 && 原.附件) await 刪附件(原.附件);
          值.附件 = 路徑;
          值.檔名 = 檔.name;
        } catch (e) { return e.message; }
      }
    }
    if (原) 更新紀錄(定.集合, id, 值); else 新增紀錄(定.集合, 值);
    提示("已儲存，發布到官網後才會更新網站");
    完成後();
  }, 選項);
}

