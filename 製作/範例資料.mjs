// 固定亂數種子，讓每次產生的資料一樣
let 種子 = 20261008;
// 產生 0～1 的亂數（可重現）
function 亂() {
  種子 = (種子 * 1103515245 + 12345) % 2147483648;
  return 種子 / 2147483648;
}
// 從陣列隨機挑一個
function 挑(陣列) { return 陣列[Math.floor(亂() * 陣列.length)]; }
// 隨機整數（含頭尾）
function 整數(a, b) { return a + Math.floor(亂() * (b - a + 1)); }
// 補零
function 零(n, k) { return String(n).padStart(k || 2, "0"); }
// 產生編號
let 流水 = 0;
function 編號() { 流水++; return "ex" + 零(流水, 6); }
// 某日期加減天數
function 加天(日期, 天) { const d = new Date(日期 + "T00:00:00Z"); d.setUTCDate(d.getUTCDate() + 天); return d.toISOString().slice(0, 10); }
// 日期轉 ISO 時間（台灣時間）
function 時間(日期, 時分) { return new Date(日期 + "T" + (時分 || "09:00") + ":00+08:00").toISOString(); }
// 西元轉民國年
function 民國年(y) { return Number(y) - 1911; }

// 給每筆紀錄補上共同欄位
function 紀錄(物件, 日期, 修改人) {
  const t = 時間(日期 || "2026-01-05");
  return Object.assign({ id: 編號() }, 物件, { 建立時間: t, 修改時間: t, 修改人: 修改人 || "陳怡君" });
}

// PBKDF2 密碼雜湊（與會務系統相同參數）
function 密碼(明文) {
  const 鹽 = crypto.randomBytes(16).toString("hex");
  const 次數 = 310000;
  return { 鹽, 次數, 雜湊: crypto.pbkdf2Sync(明文, Buffer.from(鹽, "hex"), 次數, 32, "sha256").toString("hex") };
}

